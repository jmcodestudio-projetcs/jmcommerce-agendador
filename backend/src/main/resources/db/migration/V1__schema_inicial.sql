-- V1__schema_inicial.sql
-- Agendamento para fotografos - schema inicial (PostgreSQL)
-- Local no projeto: src/main/resources/db/migration/

-- ---------------------------------------------------------------
-- FOTOGRAFO: a conta que faz login no painel
-- ---------------------------------------------------------------
CREATE TABLE fotografo (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                        VARCHAR(120) NOT NULL,
    email                       VARCHAR(160) NOT NULL,
    senha_hash                  VARCHAR(100) NOT NULL,
    slug                        VARCHAR(60)  NOT NULL,
    telefone_whatsapp           VARCHAR(20),
    bio                         VARCHAR(500),
    status_assinatura           VARCHAR(20)  NOT NULL DEFAULT 'TESTE',
    teste_ate                   DATE         NOT NULL,
    -- "esqueci minha senha": token unico guardado na propria conta
    token_redefinicao           VARCHAR(64),
    token_redefinicao_expira_em TIMESTAMPTZ,
    criado_em                   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_fotografo_email UNIQUE (email),
    CONSTRAINT uq_fotografo_slug  UNIQUE (slug),
    CONSTRAINT ck_fotografo_slug  CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_fotografo_status_assinatura
        CHECK (status_assinatura IN ('TESTE', 'ATIVA', 'SUSPENSA'))
);

-- ---------------------------------------------------------------
-- SERVICO: o que o fotografo oferece
-- ---------------------------------------------------------------
CREATE TABLE servico (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fotografo_id    BIGINT       NOT NULL REFERENCES fotografo (id),
    nome            VARCHAR(120) NOT NULL,
    descricao       VARCHAR(500),
    duracao_minutos INTEGER      NOT NULL,
    preco           NUMERIC(10, 2),
    exibir_preco    BOOLEAN      NOT NULL DEFAULT FALSE,
    ativo           BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_servico_duracao CHECK (duracao_minutos > 0),
    CONSTRAINT ck_servico_preco   CHECK (preco IS NULL OR preco >= 0)
);

CREATE INDEX ix_servico_fotografo ON servico (fotografo_id);

-- ---------------------------------------------------------------
-- HORARIO_DISPONIVEL: cada linha = um horario aberto = uma sessao
-- ---------------------------------------------------------------
CREATE TABLE horario_disponivel (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fotografo_id BIGINT NOT NULL REFERENCES fotografo (id),
    data         DATE   NOT NULL,
    hora         TIME   NOT NULL,

    -- impede abrir o mesmo horario duas vezes e ja serve de indice
    -- para as consultas por fotografo + periodo
    CONSTRAINT uq_horario_fotografo_data_hora UNIQUE (fotografo_id, data, hora)
);

-- ---------------------------------------------------------------
-- AGENDAMENTO: o pedido do cliente (cliente nao tem conta)
-- ---------------------------------------------------------------
CREATE TABLE agendamento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fotografo_id     BIGINT       NOT NULL REFERENCES fotografo (id),
    servico_id       BIGINT       NOT NULL REFERENCES servico (id),
    -- fica NULL se o fotografo apagar o horario de um pedido ja encerrado
    horario_id       BIGINT       REFERENCES horario_disponivel (id) ON DELETE SET NULL,
    -- copia da data/hora: o historico continua legivel sem o horario
    data             DATE         NOT NULL,
    hora             TIME         NOT NULL,
    codigo           VARCHAR(32)  NOT NULL,
    status           VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
    cliente_nome     VARCHAR(120) NOT NULL,
    cliente_email    VARCHAR(160) NOT NULL,
    cliente_telefone VARCHAR(20),
    observacao       VARCHAR(1000),
    motivo           VARCHAR(500),
    criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_agendamento_codigo UNIQUE (codigo),
    CONSTRAINT ck_agendamento_status
        CHECK (status IN ('PENDENTE', 'APROVADO', 'RECUSADO', 'CANCELADO')),
    -- pedido ativo sempre tem horario: o banco recusa apagar o horario
    -- de um agendamento pendente ou aprovado
    CONSTRAINT ck_agendamento_ativo_tem_horario
        CHECK (horario_id IS NOT NULL OR status IN ('RECUSADO', 'CANCELADO'))
);

-- REGRA CENTRAL: no maximo um agendamento ativo por horario.
-- Dois clientes no mesmo horario -> o segundo INSERT falha aqui
-- e a API responde 409 HORARIO_INDISPONIVEL.
CREATE UNIQUE INDEX ux_agendamento_horario_ativo
    ON agendamento (horario_id)
    WHERE status IN ('PENDENTE', 'APROVADO');

-- listagem do painel: por fotografo, periodo e status
CREATE INDEX ix_agendamento_fotografo_data ON agendamento (fotografo_id, data, hora);
